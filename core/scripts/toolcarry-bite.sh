#!/usr/bin/env bash
# Стенд укуса scripts/toolcarry.py: замер переноса вывода инструментов.
#
#   bash ~/.claude/scripts/toolcarry-bite.sh
#   TOOLCARRY=/путь/к/другому bash ~/.claude/scripts/toolcarry-bite.sh
#
# Зачем в репозитории: на этот скрипт опирается проба живой строки реестра
# (home/20260912-01), а сам он режет транскрипт на ходы по неочевидным
# правилам. Ошибка в нарезке не падает и не шумит — она выдаёт круглое
# правдоподобное число. Первая редакция замера так дала 89,6% «нулевого
# переноса»: цифру красивую и целиком ложную.
#
# 🔴 ЗАМЕРЫ 12.09.2026 (14 укусов, 13 мутаций). Стенд, не умеющий краснеть,
# охраняет ничего:
#   живой toolcarry.py ......................... ✅ 14  ❌ 0
#   13 мутаций ................................. каждая роняет РОВНО свой укус
#   из них частичная (одно вхождение из двух) .. 1 — и она тоже краснеет
#
# Укусы спаяны попарно там, где отрицание зелено само по себе: «переноса нет»
# истинно и у сломанного счётчика. Поэтому рядом с каждым нулём в ТОМ ЖЕ
# утверждении стоит соседняя фикстура, где перенос обязан быть.
#
# 🔴 Живой корпус ~/.claude/projects стенд НЕ трогает: он растёт каждым ходом,
# и фикстура, которую производит сама проверяемая сессия, — не фикстура.
T="${TOOLCARRY:-$HOME/.claude/scripts/toolcarry.py}"
ROOT="$(mktemp -d)"; trap 'rm -rf "$ROOT"' EXIT
pass=0; fail=0
is() { if [ "${2:-1}" = 0 ]; then echo "  ✅ $1"; pass=$((pass+1));
       else echo "  ❌ $1"; fail=$((fail+1)); fi; }

# --- сборка фикстур -------------------------------------------------------
# Записи транскрипта. Литеральное \n внутри аргумента остаётся экранированным
# переводом строки JSON — в выводе инструмента это настоящая строка.
new() { F="$ROOT/$1"; mkdir -p "$F"; }               # new <каталог-корень>
au() { printf '{"type":"assistant","message":{"content":[{"type":"tool_use","id":"%s","name":"%s","input":%s}]}}\n' \
         "$2" "$3" "$4" >> "$1"; }                   # au <файл> <id> <имя> <input-json>
ur() { printf '{"type":"user","message":{"content":[{"type":"tool_result","tool_use_id":"%s","content":"%s"}]}}\n' \
         "$2" "$3" >> "$1"; }                        # ur <файл> <id> <вывод>
at() { printf '{"type":"assistant","message":{"content":[{"type":"text","text":"%s"}]}}\n' "$2" >> "$1"; }
ut() { printf '{"type":"user","message":{"content":[{"type":"text","text":"%s"}]}}\n' "$2" >> "$1"; }
pad() { printf '%*s' "$1" '' | tr ' ' x; }

# Один вызов Bash, вывод <3>, следующий ход ассистента говорит <4>.
simple() {  # simple <файл> <команда> <вывод> <текст следующего хода>
  au "$1" t1 Bash "{\"command\":\"$2\"}"; ur "$1" t1 "$3"; at "$1" "$4"; ut "$1" ок
}

# --- прогон и разбор отчёта ----------------------------------------------
run() { out="$(python3 "$T" "$@" 2>"$ROOT/err")"; rc=$?; err="$(cat "$ROOT/err")"; }
f_calls()  { printf '%s' "$out" | sed -n 's/.*· вызовов \([0-9,]*\) ·.*/\1/p' | tr -d ,; }
f_files()  { printf '%s' "$out" | sed -n 's/^файлов \([0-9]*\) .*/\1/p'; }
f_bad()    { printf '%s' "$out" | sed -n 's/^файлов [0-9]* (нечитаемых \([0-9]*\)).*/\1/p'; }
f_strict() { printf '%s' "$out" | sed -n 's/^перенос: строгий (новое) \([0-9.]*\)%.*/\1/p'; }
f_soft()   { printf '%s' "$out" | sed -n 's/.*мягкий (любой токен) \([0-9.]*\)%.*/\1/p'; }
f_next()   { printf '%s' "$out" | sed -n 's/.*в следующий ход \([0-9.]*\)%.*/\1/p'; }
f_dead()   { printf '%s' "$out" | sed -n 's/^вызовов, чей вывод не всплыл нигде: \([0-9,]*\) .*/\1/p' | tr -d ,; }
# Проценты печатаются через %.1f — ноль это ровно «0.0», сравнение строкой честно.
gt0()  { [ -n "$1" ] && [ "$1" != "0.0" ]; }
zero() { [ "$1" = "0.0" ]; }

echo "=== нарезка ходов, новизна токена и окно ==="

# УКУС 1. Ход ассистента — это ВСЕ его записи подряд, а не первая. Перенос
# лежит во второй записи хода, первая пуста. Спаяно с фикстурой без переноса:
# «нуля нет» в одиночку зеленеет на любом сломанном счётчике.
new t1a; A="$F/s.jsonl"
au "$A" t1 Bash '{"command":"grep пусто"}'; ur "$A" t1 'маяк-альфа светит'
at "$A" ''; at "$A" 'ход продолжается маяк-альфа'; ut "$A" ок
new t1b; B="$F/s.jsonl"
au "$B" t1 Bash '{"command":"grep пусто"}'; ur "$B" t1 'маяк-альфа светит'
at "$B" ''; at "$B" 'ход продолжается без находки'; ut "$B" ок
run "$ROOT/t1a"; a_next="$(f_next)"
run "$ROOT/t1b"; b_strict="$(f_strict)"
{ gt0 "$a_next" && zero "$b_strict"; }
is "ход склеен из всех записей: перенос во ВТОРОЙ записи виден, а без него ноль" $?

# УКУС 2. Токен самой команды переносом не считается — иначе `grep X` всегда
# «уезжает» собственным аргументом. Спаяно: рядом токен, которого в команде нет.
# 🔴 Утверждать надо про МЯГКИЙ счёт, а не про строгий. Токены команды лежат в
# записи с tool_use, то есть всегда РАНЬШЕ своего вывода, и строгий счёт всё
# равно отбросил бы их вторым фильтром — новизной. Первая редакция укуса
# смотрела на строгий и на мёртвых: мутация `lt = toks(ln) - ct` → `toks(ln)`
# проезжала зелёной при исправном сторожe и исправном коде.
new t2a; A="$F/s.jsonl"; simple "$A" 'grep эхолот-зеро' 'эхолот-зеро' 'нашлось эхолот-зеро'
new t2b; B="$F/s.jsonl"
simple "$B" 'grep эхолот-зеро' 'эхолот-зеро\nи рядом гагара-семь' 'нашлось эхолот-зеро и гагара-семь'
run "$ROOT/t2a"; a_soft="$(f_soft)"; a_strict="$(f_strict)"; a_dead="$(f_dead)"
run "$ROOT/t2b"; b_soft="$(f_soft)"; b_strict="$(f_strict)"
{ zero "$a_soft" && zero "$a_strict" && [ "$a_dead" = 1 ] && gt0 "$b_soft" && gt0 "$b_strict"; }
is "эхо аргумента не переносится даже мягким счётом (вызов мёртв), чужой токен — да" $?

# УКУС 3. Строгий счёт требует НОВИЗНЫ: токен, звучавший до вывода, уехал не
# из вывода. Мягкий счёт его засчитывает — обе половины в одном утверждении.
new t3; A="$F/s.jsonl"
at "$A" 'раньше по сессии токен-бета'; ut "$A" ок
au "$A" t1 Bash '{"command":"ls"}'; ur "$A" t1 'вывод токен-бета'
at "$A" 'потом токен-бета'; ut "$A" ок
run "$ROOT/t3"
{ zero "$(f_strict)" && gt0 "$(f_soft)"; }
is "токен звучал ДО вывода: строгий ноль, мягкий — нет (вилка расходится)" $?

# УКУС 4. Окно. Одна фикстура, два утверждения: отбор вызовов и предел переноса.
# Горизонт «до конца сессии» врёт усечением справа — у позднего вызова просто
# нет сессии впереди; падение 52%→11% однажды оказалось наполовину артефактом.
new t4; A="$F/s.jsonl"
au "$A" t1 Bash '{"command":"ls"}'; ur "$A" t1 'вывод маяк-дельта'
at "$A" "$(pad 3600)"; ut "$A" ок
at "$A" 'потом маяк-дельта'; ut "$A" ок
at "$A" "$(pad 8400)"; ut "$A" ок
run "$ROOT/t4" --window 100000; wide_calls="$(f_calls)"
run "$ROOT/t4" --window 1000;   narrow_calls="$(f_calls)"; narrow_strict="$(f_strict)"
{ [ "$wide_calls" = 0 ] && [ "$narrow_calls" = 1 ]; }
is "окно шире остатка сессии — вызов отброшен, а не посчитан усечённым" $?
run "$ROOT/t4" --window 5000; wide5_strict="$(f_strict)"
{ zero "$narrow_strict" && gt0 "$wide5_strict"; }
is "перенос считается только внутри окна: ход на ≈3636 вне 1000, но внутри 5000" $?

# УКУС 5. `cd X && cd Y && git ...` — это git. Без снятия префикса разбивка
# отдавала 59% знаков корпуса команде `cd` и не объясняла ничего. Префиксов
# два: снятие обязано повториться.
new t5; A="$F/s.jsonl"
simple "$A" 'cd ~/dev/x && cd ~/dev/y && git log --oneline' 'вывод маяк-гамма' 'потом маяк-гамма'
run "$ROOT/t5"
{ printf '%s' "$out" | grep -qE '^git +[0-9]' && ! printf '%s' "$out" | grep -qE '^cd +[0-9]'; }
is "двойной префикс cd снят: в таблице команд строка git, строки cd нет" $?

# УКУС 6. Три исхода пробы. Третий — не придирка: код ≠ 0 реестр читает как
# unreachable, а подмена нулём вернула бы ложь в тишину.
new t6; A="$F/s.jsonl"; simple "$A" 'ls' 'вывод маяк-омега' 'потом маяк-омега'
run "$ROOT/t6" --probe --min-calls 1 --baseline 0
{ [ "$rc" = 0 ] && printf '%s' "$out" | grep -q 'КАРТИНА-ДЕРЖИТСЯ'; }
is "проба: мёртвых 0% при базе 0 — КАРТИНА-ДЕРЖИТСЯ кодом 0" $?
run "$ROOT/t6" --probe --min-calls 1 --baseline 90
{ [ "$rc" = 0 ] && printf '%s' "$out" | grep -q 'КАРТИНА-ИЗМЕНИЛАСЬ'; }
is "проба: та же фикстура при базе 90 — КАРТИНА-ИЗМЕНИЛАСЬ кодом 0" $?
run "$ROOT/t6" --probe --min-calls 500
{ [ "$rc" = 2 ] && [ -z "$out" ] && printf '%s' "$err" | grep -q 'отвечать не на чем'; }
is "проба: данных мало — код 2 и жалоба в stderr, а не тихий вердикт" $?

echo
echo "=== живучесть обхода и отборы файлов ==="

# УКУС 7. Битый .jsonl не роняет прогон и не съедает соседей. Битый сделан
# СВЕЖЕЕ здорового: он идёт первым в сортировке по mtime, и `break` вместо
# `continue` тут однажды дал пустой вывод без единой ошибки.
new t7; A="$F/ok.jsonl"; simple "$A" 'ls' 'вывод маяк-йота' 'потом маяк-йота'
printf 'не json вовсе\n' > "$F/bad.jsonl"; touch -t 203001010000 "$F/bad.jsonl"
run "$ROOT/t7"
{ [ "$rc" = 0 ] && [ "$(f_bad)" = 1 ] && [ "$(f_files)" = 1 ] && [ "$(f_calls)" = 1 ]; }
is "битый файл впереди по mtime: код 0, нечитаемых 1, а здоровый сосед посчитан" $?

# УКУС 8. Пустой вывод вызовом не считается — иначе знаменатель «мёртвых»
# раздувается тишиной. Спаяно со счётом соседнего, непустого.
new t8; A="$F/s.jsonl"
au "$A" t1 Bash '{"command":"ls"}'; ur "$A" t1 ''
au "$A" t2 Bash '{"command":"ls"}'; ur "$A" t2 'вывод маяк-эпсилон'
at "$A" 'потом маяк-эпсилон'; ut "$A" ок
run "$ROOT/t8"
{ [ "$(f_calls)" = 1 ] && gt0 "$(f_strict)"; }
is "пустой вывод не вызов: вызовов 1 из двух, и непустой сосед посчитан" $?

# УКУС 9. Три отбора. Каждый спаян со своим «без ключа» — иначе снятый отбор
# неотличим от отбора работающего.
new t9tool; A="$F/s.jsonl"
au "$A" t1 Bash '{"command":"ls"}'; ur "$A" t1 'вывод маяк-ро'
au "$A" t2 Read '{"file_path":"/tmp/x.txt"}'; ur "$A" t2 'вывод маяк-сигма'
at "$A" ок; ut "$A" ок
run "$ROOT/t9tool"; all_calls="$(f_calls)"
run "$ROOT/t9tool" --tool Bash; only_calls="$(f_calls)"
{ [ "$all_calls" = 2 ] && [ "$only_calls" = 1 ]; }
is "--tool Bash: из двух вызовов остаётся один, без ключа — оба" $?

new t9recent; simple "$F/a.jsonl" 'ls' 'вывод маяк-тау' 'потом маяк-тау'
simple "$F/b.jsonl" 'ls' 'вывод маяк-ипсилон' 'потом маяк-ипсилон'
run "$ROOT/t9recent"; all_calls="$(f_calls)"
run "$ROOT/t9recent" --recent 1; one_calls="$(f_calls)"
{ [ "$all_calls" = 2 ] && [ "$one_calls" = 1 ]; }
is "--recent 1: из двух транскриптов читается один, без ключа — оба" $?

new t9mb; simple "$F/small.jsonl" 'ls' 'вывод маяк-фи' 'потом маяк-фи'
BIG="$F/big.jsonl"; au "$BIG" t1 Bash '{"command":"ls"}'
printf '{"type":"user","message":{"content":[{"type":"tool_result","tool_use_id":"t1","content":"%s"}]}}\n' \
  "$(head -c 1200000 /dev/zero | tr '\0' x)" >> "$BIG"
at "$BIG" ок; ut "$BIG" ок
run "$ROOT/t9mb"; all_calls="$(f_calls)"
run "$ROOT/t9mb" --max-mb 1; small_calls="$(f_calls)"
{ [ "$all_calls" = 2 ] && [ "$small_calls" = 1 ]; }
is "--max-mb 1: файл в 1,2 МБ пропущен, без ключа — читаются оба" $?

echo
echo "итог: ✅ $pass   ❌ $fail"
[ "$fail" = 0 ]
