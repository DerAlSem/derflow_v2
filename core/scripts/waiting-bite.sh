wake_ms() {  # wake_ms <каталог> → $out, $rc, $ms (миллисекунды)
  d="$1"; : > "$ROOT/ms"
  out="$(cd "$d" && python3 -c 'import pathlib, subprocess, sys, time
t = time.monotonic()
