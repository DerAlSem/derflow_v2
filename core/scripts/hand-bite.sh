#!/usr/bin/env bash
# Стенд укуса hand.sh: каждый гейт ломается нарочно и обязан покраснеть.
#
#   bash ~/.claude/scripts/hand-bite.sh            # текущий скрипт
#   HAND=/путь/к/старому bash ~/.claude/scripts/hand-bite.sh
#
# Испытывается hand.sh из того же каталога, что и стенд: запуск из ворктри
# гоняет файл ворктри, из корня — файл корня. HAND= подменяет его копией.
#
# Зачем он лежит в репозитории, а не в скрэтчпаде: гейт свежести оказывался
# МОЛЧА ИНЕРТЕН дважды (`-uall` 05.09.2026, `core.quotePath` 06.09.2026), и оба
# раза дефект был невидим — скрипт печатал успех. Стенд, живущий в сессии,
# умирает вместе с ней и второй раз не ловит. Прогонять после любой правки
# подбора или гейтов.
#
# Проверка самого стенда: на скрипте ДО правки 06.09.2026 он даёт 9 красных из
# 11. Зелёный стенд, ни разу не покрасневший, ничего не доказывает.
# То же для трёх укусов 07.09.2026 (имя в промпте, латиница в имени файла): на
# скрипте до правки — 2 красных из 14, на промежуточном варианте с ломаным
# шаблоном `case` — 1 красный, и это ровно тот, что ловит ложное срабатывание.
# 🔴 ЗАМЕРЫ СВОЕГО ФАЙЛА (24.11.2026, 21 укус, DF-21). Прежние блоки не
# пересчитаны: они датированные. Поломка копии: строка 195, exit 5 → exit 0 —
# снят гейт «подобранный хендофф обязан объявлять ветку».
#
#   живой, шелл ztui без подготовки ........ ✅ 21 ❌ 0
#   живой, чистая среда (без ZCODE_*) ...... ✅ 21 ❌ 0
#   заглушка (exit 0, молчит) через HAND= .. ✅ 0  ❌ 21   прежний стенд: ✅ 2 ❌ 18
#   сломанная копия через HAND= ............ ✅ 18 ❌ 3
#     та же копия, прежний стенд ............ ✅ 18 ❌ 2   те же два укуса про гейт
#   возвращён H=~/.claude/scripts/hand.sh ... ✅ 20 ❌ 1   укус про свой файл
#
#   Файл ВО ВОРКТРИ сломан, без HAND=:
#     новый стенд, из ворктри ............... ✅ 18 ❌ 3
#     корень в тот же момент ................. ✅ 20 ❌ 0   прежний стенд
#
# 📏 Заглушка прежде давала ✅ 2: два укуса с обратной иголкой («предупреждения
# быть НЕ должно») — отрицание без положительной половины. Теперь chk принимает
# четвёртый аргумент — строку, которая ОБЯЗАНА быть. Гейт строки 195 держит два
# укуса; новый укус про файл спаян с первым из них, поэтому на этой поломке
# красных три, а не два.
# 🔴 ПОСЛЕ РЕВЬЮ (24.11.2026, DF-21, 21 укус — счёт не менялся). Внесено:
# статическая половина укуса про файл — у определения H; обязательная подстрока
# укуса про файл задачи Backlog.md — из СОДЕРЖИМОГО фикстуры (стоял путь, и
# заглушка-эхо аргумента проходила); сторож в chk — обратная иголка с ожидаемым
# rc=0 без четвёртого аргумента отказывает, а не соглашается в шапке. Прежние
# блоки не пересчитаны.
#
#   живой, шелл ztui без подготовки ........ ✅ 21 ❌ 0
#   живой, чистая среда (без ZCODE_* и CLAUDE_*) ✅ 21 ❌ 0
#   заглушка (exit 0, молчит) через HAND= .. ✅ 0  ❌ 21
#   заглушка-эхо («хендофф: <аргумент>»):
#     до правки ............................ ✅ 1  ❌ 20
#     после ................................ ✅ 0  ❌ 21
#   возвращён путь через $HOME/.claude
#     в определении H ...................... ✅ 20 ❌ 1   укус про файл
#   вызов мимо "$H": до правки ✅ 21 ❌ 0,
#     после ................................ ✅ 20 ❌ 1   укус про файл
#   bash -s < стенд, cwd = core/scripts
#     корня ................................ ✅ 20 ❌ 1   укус про файл
#   source из чужого скрипта-обёртки ...... ✅ 20 ❌ 1   укус про файл
#   вызов голым именем hand.sh ............. ✅ 20 ❌ 1   укус про файл
#   в копии снят 4-й аргумент у укуса
#     «ЛАТИНСКОЕ имя файла»: до правки живой ✅ 21 ❌ 0,
#     заглушка ✅ 1 ❌ 20; после — живой .... ✅ 20 ❌ 1   отказ сторожа в chk
#     ..................................... ✅ 0  ❌ 21   заглушка
#
# Мутации — копии в скрэтчпаде, дерево не трогали; каждая — в чистой среде и из
# ztui, числа равные. Запуск — только `bash <путь>`: source, `bash -s <` и
# `bash -c` краснят укус про файл, потому что тогда его выбирает каталог
# запуска, а не чекаут стенда.
#
# 📏 Результат зависит и от живой таблицы процессов: hand.sh на сухом пути
# читает ps (name_taken), и таб с именем фикстуры — «C·имена сессий» — роняет
# старый укус «промпт НЕСЁТ имя» (замер критика ревью: с такой строкой в ps
# ✅ 20 ❌ 1 в 3 прогонах из 3, без неё ✅ 21 ❌ 0 в 3 из 3). Причина в
# испытуемом, здесь не чинилось (24.11.2026, ревью DF-21).
#
# 🔴 DF-22 (25.11.2026, 21 укус — счёт не менялся). Мигание из абзаца выше
# починено в СТЕНДЕ: имя фикстуры укуса «промпт НЕСЁТ имя» уникально на прогон
# — суффикс из хвоста каталога mktemp; живому табу с ним не совпасть. hand.sh не
# тронут: коллизию имён он разводит нарочно. Прежние блоки не пересчитаны.
#
#   живой таб со старым именем «C·имена сессий»:
#     прежний стенд, из корня ............... ✅ 20 ❌ 1   «промпт НЕСЁТ имя»
#     новый стенд, из ворктри, 3 прогона .... ✅ 21 ❌ 0   все три
#   без такого таба, 3 прогона .............. ✅ 21 ❌ 0   все три
#   чистая среда (без ZCODE_* и CLAUDE_*) ... ✅ 21 ❌ 0
#
# 🔴 Испытываемый файл — РЯДОМ СО СТЕНДОМ, как install-bite.sh берёт install.sh
# ($HERE там). Прежний путь по умолчанию, ~/.claude/scripts/hand.sh, — симлинк
# на КОРЕНЬ: стенд, пущенный из ворктри, гонял живой файл корня, был зелёным на
# любой правке ворктри и молчал о ней (24.11.2026, DF-21). Путь физический (cd -P):
# напечатанная строка называет тот чекаут, который реально проверен.
HERE="$(cd -P "$(dirname "$0")" && pwd)"      # физический core/scripts: ~/.claude/scripts — симлинк
H="${HAND:-$HERE/hand.sh}"
# 🔴 Статическая половина укуса про файл (24.11.2026, ревью DF-21). Стенд читает
# свой текст: КАЖДЫЙ запуск интерпретатора идёт через "$H" либо читает программу
# из stdin (`python3 -`). Сравнить переменную с её же определением — тавтология:
# стенд, все вызовы которого уведены в другое дерево, оставил бы живую половину
# зелёной, а первая строка называла бы «свой» файл. Комментарии не считаются;
# красный — первый аргумент интерпретатора, похожий на путь или переменную, либо
# голое имя испытуемого. Себя не прочитал (source, `bash -s <`, `bash -c`): $0 —
# не этот файл, красный: тогда файл выбирает каталог запуска. Пределы: путь
# после слова интерпретатора в текстовой строке — громкое ложное красное; тело
# `python3 - <<…` не читается.
self="$0"; bypass="не прочитал свой текст: $0"
[ "$self" = "${BASH_SOURCE[0]:-}" ] && [ -r "$self" ] && bypass="$(sed 's/^/ /' "$self" \
  | grep -vE '^[[:space:]]*#' \
  | grep -oE '.(python3?|bash|sh)[[:space:]]+("[^"]*"|[^[:space:]]+)' \
  | grep -E '^[^[:alnum:]_./"-]' | sed -E 's/^.(python3?|bash|sh)[[:space:]]+//' \
  | grep -vxF -e '"$H"' -e '-' \
  | grep -E -e '^[^[:alnum:][:space:]]' -e '/' -e '^hand\.sh$')"
ROOT="$(mktemp -d)"; trap 'rm -rf "$ROOT"' EXIT
pass=0; fail=0

mk() {  # mk <имя> <ветка>  → печатает путь к свежему репо
  d="$ROOT/$1"; mkdir -p "$d"; cd "$d"
  git init -q -b "$2" . ; git config user.email t@t; git config user.name t
  echo x > .keep; git add -A; git commit -qm init
  printf '%s' "$d"
}
chk() {  # chk <ожидаемый rc> <ярлык> [<иголка> [<подстрока, которая ОБЯЗАНА быть>]]
  want="$1"; label="$2"; needle="${3:-}"; must="${4:-}"
  # 🔴 Обратная иголка с ожидаемым rc=0 без положительной половины — не укус, а
  # разрешение молчать: заглушка проходит его даром. Отказ здесь, а не соглашение
  # в шапке (24.11.2026, ревью DF-21).
  case "$needle" in '!'*) case "$must$want" in
        0) echo "  ❌ $label — обратная иголка без 4-го аргумента chk: заглушке зелено даром"
           fail=$((fail+1)); ARG=""; return ;; esac ;; esac
  out="$(bash "$H" -n "$D" ${ARG:+"$ARG"} 2>&1)"; rc=$?
  ok=1
  [ "$rc" = "$want" ] || ok=0
  # Иголка с «!» в начале означает ОБРАТНОЕ: подстроки быть НЕ должно. Без неё
  # предупреждение, которое сработало на каждом файле подряд, стенд бы не поймал
  # — ровно так и вышло 07.09.2026: шаблон `case` с ломаным диапазоном совпадал
  # с «tab-name.md», а проверка «есть ли строка» это считает успехом.
  case "$needle" in
    '!'*) printf '%s' "$out" | grep -q -- "${needle#!}" && ok=0 ;;
    ?*)   printf '%s' "$out" | grep -q -- "$needle" || ok=0 ;;
  esac
  # 🔴 Четвёртый аргумент — положительная половина. Обратная иголка («этого быть
  # НЕ должно») зелена на молчащей заглушке даром: замер 24.11.2026, DF-21 —
  # заглушка (exit 0, молчит) давала ✅ 2 ❌ 18, и оба зелёных стояли на одном
  # отрицании. Рядом обязана стоять строка, которую печатает только работающий
  # hand.sh.
  case "$must" in
    ?*)   printf '%s' "$out" | grep -q -- "$must" || ok=0 ;;
  esac
  if [ "$ok" = 1 ]; then echo "  ✅ $label (rc=$rc)"; pass=$((pass+1))
  else
    # Иголку печатаем БЕЗ ведущего «!»: иначе `!` уедет в диагностику как часть
    # искомого текста.
    #
    # 🔴 Скобки вокруг имени ОБЯЗАТЕЛЬНЫ, и это не стиль. Комментарий, стоявший
    # здесь с 07.09.2026, винил «последовательность „« + !“» — диагноз неверен.
    # Настоящая причина: `»` многобайтовый, и его первый байт прилипает к имени
    # переменной. `«$needle»` разбирается как переменная `needle<байт>`, которой
    # нет. Под `set -u` это обрыв, без него — тихая пустота, и диагностика
    # КАЖДОГО краснеющего укуса выходила пустой ровно там, где она и нужна.
    # Репро: `bash -c 'n=abc; echo "«$n»"'` против `«${n}»`.
    case "$needle" in
      '!'*) say="и НЕ должно быть «${needle#!}»" ;;
      ?*)   say="и «${needle}»" ;;
      *)    say="" ;;
    esac
    # Скобки вокруг имени — та же причина, что выше у иголки.
    case "$must" in ?*) say="${say:+$say, }обязано быть «${must}»" ;; esac
    echo "  ❌ $label — ждали rc=$want ${say}, получили rc=$rc"
    echo "$out" | sed 's/^/       /'; fail=$((fail+1)); fi
  ARG=""
}

