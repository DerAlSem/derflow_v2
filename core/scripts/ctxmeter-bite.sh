#!/usr/bin/env bash
# Стенд укуса context-meter.py --tool: вход PostToolUse.
#
#   bash ~/.claude/scripts/ctxmeter-bite.sh
#   METER=/путь/к/старому bash ~/.claude/scripts/ctxmeter-bite.sh
#
# Испытывается context-meter.py из того же чекаута, что и стенд (файл лежит
# в core/hooks, стенд — в core/scripts): запуск из ворктри гоняет файл ворктри,
# из корня — файл корня. METER= подменяет его копией.
#
# Зачем в репозитории: хук на PostToolUse дёргается на КАЖДОМ вызове
# инструмента. Молча инертный он не заметен вовсе, а падающий ломает работу —
# оба отказа тихие, и оба ловятся только стендом.
# 🔴 ЗАМЕРЫ 12.09.2026 (7 укусов). Стенд, не умеющий краснеть, охраняет ничего:
#   живой context-meter.py ..................... ✅ 7  ❌ 0
#   заглушка (exit 0, молчит) .................. ✅ 0  ❌ 7
#   версия ДО правки (нет входа --tool) ........ ✅ 1  ❌ 6
# Ноль у заглушки — следствие спайки: каждое «молчит» стоит в одном утверждении
# с «а рядом говорит». Первая редакция стенда держала их порознь и давала
# заглушке ✅ 5 ❌ 3, то есть охраняла молчание, а не работу.
# 🔴 ЗАМЕРЫ СВОЕГО ФАЙЛА И СРЕДЫ (24.11.2026, 9 укусов, DF-21). Прежние блоки не
# пересчитаны: они датированные. Оба новых укуса проверены мутацией — откат своей
# правки краснит ровно его. Поломка копии: защёлка снята, claim(loud_latch) → True.
#
#   живой, шелл ztui без подготовки ........ ✅ 9  ❌ 0
#   живой, чистая среда (без ZCODE_*) ...... ✅ 9  ❌ 0
#   заглушка (exit 0, молчит) через METER= . ✅ 0  ❌ 9
#   сломанная копия через METER= ........... ✅ 8  ❌ 1   укус про защёлку
#     та же копия, прежний стенд ............ ✅ 6  ❌ 1   тот же укус
#   возвращён M=~/.claude/hooks/context-meter.py  ✅ 8 ❌ 1   укус про свой файл
#   снята env -u в meter():
#     чистая среда ......................... ✅ 8  ❌ 1   укус про ZCODE_SESSION_ID
#     шелл ztui без подготовки .............. ✅ 8  ❌ 1   тот же укус
#
#   Файл ВО ВОРКТРИ сломан, без METER=:
#     новый стенд, из ворктри ............... ✅ 8  ❌ 1
#     корень в тот же момент ................ ✅ 7  ❌ 0   прежний стенд, 7 укусов
#
# 📏 «Корень ✅ 7 ❌ 0» на СЛОМАННОМ файле ворктри — прежний стенд брал файл корня
# через симлинк ~/.claude/hooks; до правки из ворктри было тоже ✅ 7 ❌ 0.
# Ломать защёлку надо без вызова claim: `(claim(loud_latch) or True)` её НЕ
# снимает — файл ставится, и второй вызов молчит по раннему выходу.
# 🔴 ПОСЛЕ РЕВЬЮ (24.11.2026, DF-21, 9 укусов — счёт не менялся). Два критика
# независимо нашли одно и то же: укус про файл сравнивал переменную с её же
# определением, и стенд с вызовами, уведёнными в другое дерево, был зелёным.
# Внесено: статическая половина укуса — у определения M; укус про
# ZCODE_SESSION_ID держит и порог, и форму. Прежние блоки не пересчитаны.
#
#   живой, шелл ztui без подготовки ........ ✅ 9  ❌ 0
#   живой, чистая среда (без ZCODE_* и CLAUDE_*) ✅ 9 ❌ 0
#   заглушка (exit 0, молчит) через METER= . ✅ 0  ❌ 9
#   возвращён путь через $HOME/.claude
#     в определении M ...................... ✅ 8  ❌ 1   укус про файл
#   вызов мимо "$M": до правки ✅ 9 ❌ 0,
#     после ................................ ✅ 8  ❌ 1   укус про файл
#   bash -s < стенд, cwd = core/scripts
#     корня ................................ ✅ 8  ❌ 1   укус про файл
#   source из чужого скрипта-обёртки ...... ✅ 8  ❌ 1   укус про файл
#   вызов голым именем context-meter.py ... ✅ 8  ❌ 1   укус про файл
#   снята env -u в meter() ................. ✅ 8  ❌ 1   укус про ZCODE_SESSION_ID
#     она же и строка в stderr перед JSON
#     в копии хука: до правки ✅ 9 ❌ 0,
#     после ................................ ✅ 8  ❌ 1   тот же укус
#
# Мутации — копии в скрэтчпаде, дерево не трогали; каждая — в чистой среде и из
# ztui, числа равные. Запуск — только `bash <путь>`: source, `bash -s <` и
# `bash -c` краснят укус про файл, потому что тогда его выбирает каталог
# запуска, а не чекаут стенда.
#
# 🔴 Испытываемый файл — ИЗ ТОГО ЖЕ ЧЕКАУТА, что и стенд, как handoff-bite.sh
# берёт handoff-header.py (там путь собран прямо в HOOK=, без cd -P): файл лежит
# в core/hooks, стенд — в core/scripts. Прежний путь ~/.claude/hooks/context-meter.py —
# симлинк на КОРЕНЬ: стенд, пущенный из ворктри, гонял живой файл корня, был
# зелёным на любой правке ворктри и молчал о ней (24.11.2026, DF-21). Путь
# физический (cd -P): напечатанная строка называет тот чекаут, который реально
# проверен.
HERE="$(cd -P "$(dirname "$0")/.." && pwd)"   # физический core/
M="${METER:-$HERE/hooks/context-meter.py}"
# 🔴 Статическая половина укуса про файл (24.11.2026, ревью DF-21). Стенд читает
# свой текст: КАЖДЫЙ запуск интерпретатора идёт через "$M" либо читает программу
# из stdin (`python3 -`). Сравнить переменную с её же определением — тавтология:
# стенд, все вызовы которого уведены в другое дерево, оставил бы живую половину
# зелёной, а первая строка называла бы «свой» файл. Комментарии не считаются;
# красный — первый аргумент интерпретатора, похожий на путь или переменную, либо
# голое имя испытуемого. Себя не прочитал (source, `bash -s <`, `bash -c`): $0 —
# не этот файл, красный: тогда файл выбирает каталог запуска. Пределы: путь
# после слова интерпретатора в текстовой строке — громкое ложное красное; тело
# `python3 - <<…` не читается.
self="$0"; bypass="не прочитал свой текст: $0"
[ "$self" = "${BASH_SOURCE[0]:-}" ] && [ -r "$self" ] && bypass="$(sed 's/^/ /' "$self" \
  | grep -vE '^[[:space:]]*#' \
  | grep -oE '.(python3?|bash|sh)[[:space:]]+("[^"]*"|[^[:space:]]+)' \
  | grep -E '^[^[:alnum:]_./"-]' | sed -E 's/^.(python3?|bash|sh)[[:space:]]+//' \
  | grep -vxF -e '"$M"' -e '-' \
  | grep -E -e '^[^[:alnum:][:space:]]' -e '/' -e '^context-meter\.py$')"
ROOT="$(mktemp -d)"; trap 'rm -rf "$ROOT"' EXIT
export HOME="$ROOT/fakehome"; mkdir -p "$HOME/.claude/state"
pass=0; fail=0
is() { if [ "${2:-1}" = 0 ]; then echo "  ✅ $1"; pass=$((pass+1));
       else echo "  ❌ $1"; fail=$((fail+1)); fi; }
tr_with() {  # tr_with <контекст> → путь к транскрипту
  printf '{"type":"assistant","message":{"usage":{"input_tokens":0,"cache_creation_input_tokens":0,"cache_read_input_tokens":%s}}}\n' "$1" > "$ROOT/t$1.jsonl"
  printf '%s' "$ROOT/t$1.jsonl"
}
# 🔴 ZCODE_SESSION_ID снимается при КАЖДОМ запуске context-meter.py — здесь, в
# обёртке, а не unset наверху стенда: иммунитет проверяется укусом изнутри
# (переменную подкладывают перед вызовом), а unset сверху изнутри не поймать.
# По ZCODE_SESSION_ID context-meter.py переходит на контракт ZCode: печатает
# JSON вместо plain, берёт пороги 130k/170k вместо 150k/300k, зовёт
# ~/.zcode/scripts/hand.sh. Для хука это правильно, для стенда — чужой приказ:
# иголки «hand.sh» и «420k» переживают JSON-строку, и из шелла ztui стенд был
# зелёным на чужом контракте (24.11.2026, DF-21).
meter() {  # meter <аргументы context-meter.py…> — без переменных сессии ZCode
  env -u ZCODE_SESSION_ID python3 "$M" "$@"
}
run() {  # run <сессия> <транскрипт> → $out
  out="$(printf '{"session_id":"%s","transcript_path":"%s"}' "$1" "$2" | meter --tool 2>&1)"; rc=$?
}

# Первая строка прогона: по одному логу видно, какой файл и в каком чекауте
# проверен. Без METER= это файл того же чекаута, что и стенд, с METER= —
# названная копия.
if [ -n "${METER:-}" ]; then how="по METER="; else how="тот же чекаут, что и стенд"; fi
echo "испытываемый файл: $M — $how"
echo

echo "=== порог, защёлка и живучесть — каждое отрицание спаяно с положительным ==="

# 🔴 ПРАВИЛО УКУСА. «Молчит» зелено на заглушке: она молчит всегда и везде.
# Поэтому в КАЖДОМ утверждении рядом с тишиной стоит речь, которую даёт только
# работающий хук. Замер этого правила — ниже, в шапке замеров.
LOW="$(tr_with 120000)"; HIGH="$(tr_with 420000)"

run a1 "$LOW"; lo_rc=$rc; lo_out="$out"
run a2 "$HIGH"; hi_rc=$rc; hi_out="$out"
{ [ "$lo_rc" = 0 ] && [ -z "$lo_out" ] && [ "$hi_rc" = 0 ] \
    && printf '%s' "$hi_out" | grep -q "hand.sh"; }
is "порог различает: на 120k молчит, на 420k зовёт hand.sh" $?
{ printf '%s' "$hi_out" | grep -q "420k"; }
is "…и называет РАЗМЕР, а не только призыв: совет без числа не проверяем" $?
# 🔴 Какой файл здесь проверяется. Из ворктри стенд гонял живой файл КОРНЯ и был
# зелёным на любой правке ворктри (24.11.2026, DF-21). Спаяно с положительной
# половиной: hand.sh позвал именно этот файл — заглушке здесь зеленеть нечем.
# Статическая половина — у определения M: запуск мимо "$M" виден только по
# тексту стенда, по выводу его не отличить.
[ -z "$bypass" ] || echo "  🔴 запуск мимо переменной пути: $bypass"
{ [ "$M" = "${METER:-$HERE/hooks/context-meter.py}" ] && [ -z "$bypass" ] \
    && printf '%s' "$hi_out" | grep -q "hand.sh"; }
is "🔴 испытываемый файл — из того же чекаута, что и стенд (или назван METER=), и он же позвал hand.sh" $?

run b1 "$HIGH"; first="$out"
run b1 "$HIGH"; second="$out"
{ printf '%s' "$first" | grep -q "hand.sh" && [ -z "$second" ]; }
is "защёлка: первый вызов сессии печатает, второй молчит — 178 повторов это фон" $?
run b2 "$HIGH"
{ printf '%s' "$out" | grep -q "hand.sh"; }
is "…но защёлка ПОСЕССИОННАЯ: соседняя сессия своё предупреждение получает" $?

# 🔴 Иммунитет стенда к среде сессии (24.11.2026, DF-21). Из шелла ztui стенд
# наследует ZCODE_SESSION_ID, и context-meter.py уходил на контракт ZCode: тот
# же прогон был зелёным на JSON-выводе и порогах 130k/170k. Снимает meter() при
# каждом запуске, а здесь переменная подкладывается НАРОЧНО: иначе иммунитет
# проверен только в шелле ztui, и в чистом шелле снятая правка не краснит
# ничего. Сессия свежая: на повторной защёлка молчит и без JSON.
# Ревью DF-21 (24.11.2026) — укус держал только форму и только первым знаком
# первой строки. Теперь две половины. Порог: 120k и 420k лежат ПО ОДНУ сторону
# обоих контрактов (громкий порог 300k у Claude Code, 170k у ZCode), порог не
# видел никто — рядом встала 200k: на контракте Claude Code молчит, на ZCode
# зовёт. Форма: JSON — когда ХОТЯ БЫ ОДНА строка начинается с «{», где бы она ни
# стояла: строка в stderr перед JSON прежде проводила чужой контракт; контракт
# Claude Code узнаётся по его собственному hand.sh (loud_msg в context-meter.py).
MID="$(tr_with 200000)"
ZCODE_SESSION_ID=x run z1 "$MID"; mid_rc=$rc; mid_out="$out"
ZCODE_SESSION_ID=x run z2 "$HIGH"
{ [ "$mid_rc" = 0 ] && [ -z "$mid_out" ] \
    && printf '%s' "$out" | grep -q '\.claude/scripts/hand\.sh' \
    && ! printf '%s' "$out" | grep -q '^{'; }
is "🔴 ZCODE_SESSION_ID снаружи не переводит стенд на контракт ZCode: на 200k молчит, на 420k зовёт hand.sh, вывод остаётся plain" $?

# Хук висит на КАЖДОМ вызове инструмента: упавший ломает работу, болтливый
# засоряет. Обе стороны в одном утверждении — иначе заглушка зеленеет.
run c1 "$ROOT/НЕТ-ТАКОГО.jsonl"; a_rc=$rc; a_out="$out"
run c2 "$HIGH"; b_rc=$rc; b_out="$out"
{ [ "$a_rc" = 0 ] && [ -z "$a_out" ] && [ "$b_rc" = 0 ] \
    && printf '%s' "$b_out" | grep -q "hand.sh"; }
is "транскрипта нет — молчит кодом 0, а рядом на здоровом входе говорит" $?

printf 'не json вовсе\n' > "$ROOT/bad.jsonl"
run d1 "$ROOT/bad.jsonl"; a_rc=$rc; a_out="$out"
run d2 "$HIGH"; b_rc=$rc; b_out="$out"
{ [ "$a_rc" = 0 ] && [ -z "$a_out" ] && [ "$b_rc" = 0 ] \
    && printf '%s' "$b_out" | grep -q "hand.sh"; }
is "битый транскрипт — молчит кодом 0, а рядом на здоровом входе говорит" $?

a_out="$(printf 'не json' | meter --tool 2>&1)"; a_rc=$?
run e1 "$HIGH"
{ [ "$a_rc" = 0 ] && [ -z "$a_out" ] && printf '%s' "$out" | grep -q "hand.sh"; }
is "мусор на stdin — молчит кодом 0, а рядом на здоровом входе говорит" $?

echo
echo "итог: ✅ $pass   ❌ $fail"
[ "$fail" = 0 ]
