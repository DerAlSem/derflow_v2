#!/usr/bin/env bash
# Расщепление сессии: открыть свежую в нужном каталоге, накормив её хендоффом.
#
# Транспорт между сессиями не должен быть человеком. Состояние лежит в файле,
# поэтому промпт следующей сессии — КОНСТАНТА, а не сочинение на пике контекста.
#
#   hand.sh                      # хендофф ищется в текущем каталоге
#   hand.sh <каталог>            # ищется там
#   hand.sh <каталог> <файл>     # явный путь — ОБЯЗАТЕЛЕН там, где все сессии
#                                # сидят на одной ветке: ключ по ветке там общий
#   hand.sh -n ...               # только показать команду, не открывать таб
#
# Хендофф обязан нести шапкой две строки: «ветка:» и «имя:». Первая — КЛЮЧ, по
# ней файл и находится; вторая становится именем сессии и заголовком таба
# (`claude --name`). Конвенция — derflow/_capture.md.
#
# 🔴 Имя ФАЙЛА ключом не является и быть им не должно: пока ключевало имя, файл
# приходилось звать слагом ветки, и человеческое имя рождало второй файл под
# машинным. Зови файл по-человечески, ключ пиши в шапку.
#
# Коды отказа: 1 нет файла · 2 несвежий · 3 чужая ветка · 4 форма имени ·
#              5 автоподбор без «ветка:» · 6 несколько хендоффов на ветку.
#
# Каталог тот же — НЕ повод не звать (v4.16): короткое окно двух сессий на одном
# дереве законно, пока старый таб его больше не трогает. `/clear` — только если
# человек прямо попросил «тем же табом»; сам его не предлагай.
set -euo pipefail

# Ветка из шапки хендоффа — ПЕРВЫМ полем, а не всей строкой. Сверка полной
# строкой ломалась о любой хвост: боевое 06.09.2026 — «ветка: feature/X (ворктри
# …)» не совпало с «feature/X», шаг 1 промахнулся, и подбор свалился в корень.
# Быть строгим тут нечем: хвост в строке ничему не мешает, а несовпадение стоит
# подсунутого чужого состояния.
declared_branch() {
  grep -m1 -E '^ветка:' "$1" 2>/dev/null \
    | sed 's/^ветка:[[:space:]]*//' | awk '{print $1}' || true
}

dry=0
[ "${1:-}" = "-n" ] && { dry=1; shift; }

dir="${1:-$PWD}"
[ -d "$dir" ] || { echo "нет каталога: $dir" >&2; exit 1; }
dir="$(cd "$dir" && pwd)"

auto=0
if [ "${2:-}" ]; then
  # Второй аргумент ОБЯЗАН относиться к первому: промпт строится относительным
  # путём от каталога, и хендофф снаружи в нём не разрешится. Относительный путь
  # считаем от каталога, а не от cwd, — иначе он зависит от того, откуда позвали.
  case "$2" in
    /*) hand="$2" ;;
    *)  hand="$dir/$2" ;;
  esac
  [ -f "$hand" ] || { echo "нет файла хендоффа: $hand" >&2; exit 1; }
  hand="$(cd "$(dirname "$hand")" && pwd)/$(basename "$hand")"
  case "$hand" in
    "$dir"/*) : ;;
    *) echo "❌ ХЕНДОФФ ВНЕ КАТАЛОГА: $hand" >&2
       echo "   не внутри $dir — промпт с относительным путём не разрешится." >&2
       exit 1 ;;
  esac
else
  auto=1
  # Путь ключуется ЗАДАЧЕЙ, а не репозиторием. Общее имя в корне — общий
  # изменяемый ресурс: две сессии в одном дереве затрут хендоффы друг друга, и
  # преемник уверенно продолжит чужую работу. Порядок от уникального к общему.
  hand=""
  br="$(cd "$dir" && git rev-parse --abbrev-ref HEAD 2>/dev/null || true)"
  # 1. заявка openspec — уникальна по задаче, НО заявок в дереве много, и
  #    сестринские сессии держат свои. `head -1` брал произвольную чужую, и
  #    проверка принадлежности ниже превращала промах в ОТКАЗ вместо перебора.
  #    Поэтому кандидат обязан сам объявить текущую ветку. Не объявил никто —
  #    молча падаем на пункт 2, это и есть верное поведение.
  #    Объявили НЕСКОЛЬКО — отказ со списком, как на ступени 2. Раньше здесь
  #    стоял `break`, то есть побеждал алфавит: боевое 07.09.2026 в sms-gate —
  #    давно влитая `attribute-late-delivery-reports` переезжала живую
  #    `verify-by-inbound-code`, и преемник садился за чужую законченную работу.
  #    Заявка на стволе живёт до архивации, так что столкновение здесь — норма,
  #    а не редкость, и молчаливый выбор дороже отказа.
  nopen=0
  if [ -z "$hand" ] && [ -n "$br" ]; then
    matches=""; nmatch=0
    while IFS= read -r c; do
      [ -f "$c" ] || continue
      nopen=$((nopen + 1))
      [ "$(declared_branch "$c")" = "$br" ] || continue
      nmatch=$((nmatch + 1)); matches="${matches}${c}
"
    done < <(find "$dir/openspec/changes" -maxdepth 2 -name HANDOFF.md 2>/dev/null | sort)
    if [ "$nmatch" -gt 1 ]; then
      echo "❌ ХЕНДОФФОВ НА ВЕТКУ «${br}» НЕСКОЛЬКО — который твой, скрипт не знает:" >&2
      printf '%s' "$matches" | sed 's|^'"$dir"'/|   |' >&2
      echo "   передай нужный вторым аргументом: hand.sh <каталог> <файл>" >&2
      exit 6
    fi
    [ "$nmatch" -eq 1 ] && hand="$(printf '%s' "$matches" | head -1)"
    if [ -z "$hand" ] && [ "$nopen" -gt 0 ]; then
      echo "ℹ️  заявочных HANDOFF.md: $nopen, ни один не объявил ветку «${br}» — ищу дальше" >&2
    fi
  fi
  # 2. по ветке, ОБЪЯВЛЕННОЙ ВНУТРИ файла, — а не по его имени.
  #    Ключ именем заставлял звать файл слагом ветки, и человеческое имя
  #    порождало ВТОРОЙ файл под машинным: боевое 06.09.2026 — сессия сделала
  #    `git mv inbox-push-and-move-trace.md feature-inbox-push-and-move-trace.md`,
  #    чтобы попасть в шаблон. Задвоение — следствие ключа, а не небрежности.
  #    Теперь имя файла человеческое по построению, ключ живёт в шапке.
  if [ -z "$hand" ] && [ -n "$br" ]; then
    matches=""; nmatch=0
    for c in "$dir"/.claude/handoff/*.md "$dir"/handoff/*.md; do
      [ -f "$c" ] || continue
      [ "$(declared_branch "$c")" = "$br" ] || continue
      nmatch=$((nmatch + 1)); matches="${matches}${c}
"
    done
    # Несколько хендоффов на одну ветку — это ствол либо забытый файл. Угадывать
    # нечем и незачем: чужое состояние выглядит валидным, а стоит переделанной
    # работы. Отказ со списком, а не «взял первый».
    if [ "$nmatch" -gt 1 ]; then
      echo "❌ ХЕНДОФФОВ НА ВЕТКУ «${br}» НЕСКОЛЬКО — который твой, скрипт не знает:" >&2
      printf '%s' "$matches" | sed 's|^'"$dir"'/|   |' >&2
      echo "   передай нужный вторым аргументом: hand.sh <каталог> <файл>" >&2
      exit 6
    fi
    [ "$nmatch" -eq 1 ] && hand="$(printf '%s' "$matches" | head -1)"
  fi
  # 3. корень — совместимость со старой конвенцией, столкновению открыт
  if [ -z "$hand" ]; then
    for c in "$dir/HANDOFF.md" "$dir/ПРОДОЛЖИТЬ.md"; do
      [ -f "$c" ] && { hand="$c"
        echo "⚠️  хендофф лежит в корне — общее имя на весь репозиторий." >&2
        echo "    две сессии в одном дереве затрут его друг другу; перенеси в" >&2
        echo "    .claude/handoff/<человеческий-слаг>.md либо к артефактам заявки." >&2
        echo "    имя файла любое — ключ живёт в строке «ветка:» внутри него." >&2
        break; }
    done
  fi
fi

if [ -z "$hand" ] || [ ! -f "$hand" ]; then
  echo "хендоффа не найдено в $dir" >&2
  echo "создай HANDOFF.md — без него расщеплять нечем: состояние передаётся файлом" >&2
  exit 1
fi
hand="$(cd "$(dirname "$hand")" && pwd)/$(basename "$hand")"

# Имя файла не ключ (см. шапку), но и не свободно: кириллица в нём уже стоила
# молча инертного гейта свежести — git печатает не-ASCII имя как
# «"\320\277..."», вместе с кавычками, и `[ -f ]` на нём ложна. Дырку заткнул
# `core.quotePath=false`, однако полагаться на один флаг там, где имя выбирает
# человек, незачем. Предупреждение, а не отказ: файл уже написан, и запрет
# продолжать по нему стоил бы дороже, чем сама проблема.
#
# 🔴 Проверять НЕ `case` с шаблоном `*[!\ -~]*`: внутри скобок экранированный
# пробел ломает диапазон, и шаблон совпадает с ЛЮБЫМ именем — «tab-name.md» в
# том числе (замер 07.09.2026, первый же прогон). Байтовая проверка `LC_ALL=C`
# однозначна и от локали не зависит.
#
# `backlog/` исключён: в docflow хендофф — файл задачи, имя ему даёт Backlog.md
# из заголовка, сессия его не выбирает. Совет «зови латиницей» там невыполним и
# бил по каждой передаче; реальную дырку и так держит `core.quotePath=false`.
case "$hand" in
  "$dir"/backlog/*) latin_check=0 ;;
  *)                latin_check=1 ;;
esac
if [ "$latin_check" = 1 ] \
   && printf '%s' "$(basename "$hand")" | LC_ALL=C grep -q '[^ -~]'; then
  echo "⚠️  имя файла хендоффа не в латинице: $(basename "$hand")" >&2
  echo "    ключ живёт в строке «ветка:», имя файла свободно —" >&2
  echo "    зови латинским слагом задачи: inbox-push-trace.md" >&2
fi

# Чужой хендофф опаснее отсутствующего: он выглядит валидным. Проверяем
# принадлежность ДО свежести — мерить свежесть чужого файла бессмысленно, а
# порядок «сначала свежесть» прятал подмену за понятной жалобой на дату.
declared="$(declared_branch "$hand")"
cur="$(cd "$dir" && git rev-parse --abbrev-ref HEAD 2>/dev/null || true)"
if [ -n "$declared" ] && [ -n "$cur" ] && [ "$declared" != "$cur" ]; then
  echo "❌ ХЕНДОФФ ОТ ДРУГОЙ ЗАДАЧИ: в нём объявлена ветка «${declared}», текущая «${cur}»." >&2
  echo "   Это чужое состояние — продолжать по нему нельзя." >&2
  exit 3
fi
# Подобранный САМ файл без строки «ветка:» — единственная дырка, через которую
# уезжало чужое состояние: шаги 1–2 доказывают принадлежность по построению, а
# фолбэк в корень не доказывает ничего. Раньше здесь стояло предупреждение в
# stderr, и оно проехало мимо глаз дважды за одно утро 06.09.2026 — обе сессии
# получили корневой `HANDOFF.md` чужой линии, и человек переоткрывал таб руками.
# Названный вручную файл остаётся предупреждением: выбор сделал человек.
if [ -z "$declared" ]; then
  if [ "$auto" = 1 ]; then
    echo "❌ ПОДОБРАННЫЙ ХЕНДОФФ НЕ ОБЪЯВЛЯЕТ ВЕТКУ — принадлежность недоказуема:" >&2
    echo "   $hand" >&2
    echo "   допиши первой строкой «ветка: ${cur:-<ветка>}» либо передай файл" >&2
    echo "   вторым аргументом: hand.sh <каталог> <файл>" >&2
    exit 5
  fi
  echo "⚠️  в хендоффе нет строки «ветка:» — принадлежность не проверяется" >&2
fi

# Несвежий хендофф хуже отсутствующего: следующая сессия поверит устаревшему
# тексту и переделает сделанное. Сравниваем с самым новым изменением в дереве.
# Гейт дважды оказывался МОЛЧА ИНЕРТЕН, и оба раза из-за формы вывода git:
#
# * `-uall` обязателен: без него git схлопывает неотслеживаемый каталог в одну
#   запись `?? .claude/`, `[ -f ]` на ней ложна, и `newest` выходит ПУСТЫМ —
#   ровно там, где хендофф и лежит (замер 05.09.2026);
# * `core.quotePath=false` обязателен: по умолчанию git печатает не-ASCII имя
#   как `"\320\277..."`, вместе с кавычками, и `[ -f ]` снова ложна. В этих
#   репозиториях кириллические имена обычны — `ПРОДОЛЖИТЬ.md` в списке фолбэка
#   сам такой (стенд укуса 06.09.2026).
#
# `cut -c4-` вместо `awk '{print $NF}'`: имя с пробелом — не последнее поле, а
# весь хвост записи после трёхзначного префикса `XY `.
newest="$(cd "$dir" && git -c core.quotePath=false status --porcelain -uall 2>/dev/null \
          | cut -c4- \
          | while IFS= read -r f; do [ -f "$f" ] && stat -f '%m' "$f"; done \
          | sort -rn | head -1 || true)"
if [ -n "$newest" ] && [ "$newest" -gt "$(stat -f '%m' "$hand")" ]; then
  echo "⚠️  ХЕНДОФФ СТАРШЕ ПОСЛЕДНИХ ПРАВОК — обнови его до расщепления," >&2
  echo "    иначе свежая сессия начнёт с устаревшего состояния." >&2
  echo "    $hand" >&2
  exit 2
fi


rel="${hand#$dir/}"

# Имя сессии. Claude Code ставит заголовок терминала САМ, на старте
# (`ESC]0;✳ Claude Code`), и любой OSC-заголовок из лаунчера затирает — замер
# 05.09.2026 под pty. Единственный рычаг — флаг `--name`; с ним заголовок
# становится `✳ <имя>`. Значит имя обязано приехать из хендоффа, как и ветка.
sess="$(grep -m1 -E '^имя:' "$hand" 2>/dev/null | sed 's/^имя:[[:space:]]*//' || true)"
if [ -z "$sess" ]; then
  # Фолбэк нарочно тупой и заметно хуже канонного: он не должен выглядеть
  # достаточным. Задача — имя ветки, а на месте буквы стоит «?».
  #
  # 🔴 Раньше буква бралась ПЕРВОЙ ОТ КАТАЛОГА, и этим фолбэк своё же требование
  # нарушал: «буква·задача» — это и есть форма ЗАКОННОГО имени, поэтому аварийное
  # имя выглядело штатным. Боевое 12.09.2026: ворктри team-roster-releases дал
  # «T·fix/team-roster-releases-the-cancelled», а T в карте занята cpvs-tbank —
  # таб стал неотличим от его сессии, и предупреждение на stderr этого не спасло.
  # «?» проектом притвориться не может ни при каком каталоге.
  sess="?·${br:-$(basename "$hand" .md)}"
  echo "⚠️  в хендоффе нет строки «имя:» — таб будет назван «${sess}»" >&2
  echo "    канон: имя: <буква проекта>·<задача>, см. derflow/_capture.md" >&2
# Гейт смотрел на НАЛИЧИЕ строки, а не на её ФОРМУ, и имя без буквы проезжало
# молча: боевое 05.09.2026 — таб назвался «ссылка-в-Штабе» вместо «G·ссылка»,
# ровно так и было вписано сессией, делавшей сплит. Отказ, а не предупреждение:
# stderr тут уже проехал мимо глаз однажды, а починка стоит одну строку в
# хендоффе. Соседние гейты скрипта (несвежесть, чужая ветка) тоже отказывают
# кодом — форма имени не исключение.
#
# Проверяем ФОРМУ, но не БУКВУ: карта проектов живёт в каноне (derflow/
# _capture.md), и копия её здесь была бы вторым источником правды, который
# разъедется молча. Поэтому «E·feat/...» гейт пропускает — форма верна, а то,
# что буква не из карты, ловится глазом, не скриптом.
elif ! printf '%s' "$sess" | grep -qE '^[[:alpha:]]·.+$'; then
  echo "❌ ИМЯ НЕ В КАНОННОЙ ФОРМЕ: «${sess}»" >&2
  echo "   канон: имя: <буква проекта>·<задача> — одна буква, разделитель «·»." >&2
  echo "   карта букв — derflow/_capture.md" >&2
  echo "   поправь строку «имя:» и позови снова: $hand" >&2
  exit 4
fi

# Омоглиф: кириллическая буква, чей латинский двойник НЕОТЛИЧИМ в табе. Буква
# стоит первой ровно затем, чтобы таб опознавался по первому знаку — а «Т·» и
# «T·» на экране один и тот же знак, и один из них уже занят картой.
#
# Карта проектов сюда НЕ копируется (довод прежний: второй источник правды
# разъедется молча). Набор двойников от карты не зависит — это свойство
# алфавитов, а не проектов. Поэтому `Л` (muzloto) проезжает: латинского
# двойника у неё нет, и запрет на всю кириллицу сломал бы живой проект.
case "$sess" in
  А·*|а·*) twin=A ;;  В·*|в·*) twin=B ;;  Е·*|е·*) twin=E ;;
  К·*|к·*) twin=K ;;  М·*|м·*) twin=M ;;  Н·*|н·*) twin=H ;;
  О·*|о·*) twin=O ;;  Р·*|р·*) twin=P ;;  С·*|с·*) twin=C ;;
  Т·*|т·*) twin=T ;;  У·*|у·*) twin=Y ;;  Х·*|х·*) twin=X ;;
  *) twin="" ;;
esac
if [ -n "$twin" ]; then
  echo "❌ ОМОГЛИФ В ИМЕНИ: «${sess}»" >&2
  echo "   первая буква кириллическая, а в табе она неотличима от латинской" >&2
  echo "   «${twin}» — и та уже может принадлежать другому проекту." >&2
  echo "   поставь латинскую букву из карты (derflow/_capture.md) и позови" >&2
  echo "   снова: $hand" >&2
  exit 4
fi

# Имя стоит В ПРОМПТЕ, а не только во флаге `--name`, — и это не дублирование.
# Claude Code генерирует имя сессии ИЗ ПЕРВОГО ПРОМПТА, когда флага нет
# (`generateSessionName` в бинаре, 2.1.236). Промпт же по канону КОНСТАНТА,
# одинаковая у всех расщеплений, — значит и сгенерированное имя одинаково и
# бессодержательно. Боевое 07.09.2026: таб назвался «Продолжение handoff», и
# так назвалась бы любая сессия, открытая руками.
#
# Флаг чинит только тот путь, где таб открывает скрипт. Ручной путь (`/clear` +
# вставленная константа) флага не имеет по построению, и починить его можно
# ровно одним способом — положить имя в саму константу. Тогда автоимя
# наследует задачу, а не слово «handoff».
prompt="${sess} — прочитай ${rel}: там всё состояние и порядок шагов. Продолжай."

echo "каталог: $dir"
echo "хендофф: $rel"
echo "имя:     $sess"
echo "промпт:  $prompt"
# Ни ${var@Q} (нет в bash 3.2), ни printf %q (он разносит UTF-8 по байтам, а
# промпт русский). Оборачиваем в одинарные кавычки, экранируя только их сами.
sq() { printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"; }
q_dir="$(sq "$dir")"
q_prompt="$(sq "$prompt")"
q_sess="$(sq "$sess")"

# 🔴 PATH у порождённого таба ГОЛЫЙ, и это не догадка (боевое 12.09.2026: таб
# открылся и напечатал «claude не найден в PATH», PATH=
# `/usr/bin:/bin:/usr/sbin:/sbin:/Applications/Ghostty.app/Contents/MacOS`).
# Лончер запускается как `#!/bin/zsh` — оболочкой НЕ login и НЕ интерактивной,
# поэтому ни `~/.zprofile`, ни `~/.zshrc` не читаются, а `claude` живёт в
# `/opt/homebrew/bin` (симлинк на каск). Расщепление молча не работало.
#
# Лечение — отдать ребёнку PATH РОДИТЕЛЯ, а не надеяться на профиль: у
# родителя он заведомо рабочий, этот скрипт из него и запущен. Названный
# отказ: `#!/bin/zsh -l` тоже читает профиль, но зависит от его содержимого и
# печатает в таб всё, что профиль печатает, — а лончер там не один, он
# `exec`ается в сессию.
#
# Вдобавок `claude` зовётся АБСОЛЮТНЫМ путём: тогда сессия стартует даже при
# испорченном PATH, а сам PATH нужен уже её хукам и скриптам (`python3`, `git`,
# `openspec`) — им абсолютного пути никто не подставит.
q_path="$(sq "$PATH")"
q_claude="$(sq "$(command -v claude 2>/dev/null || echo claude)")"

# Транспорт — ТАБ в РАБОТАЮЩЕМ инстансе, а не новый инстанс.
#
# 🔴 `open -na` открывает не «новое окно», а НОВЫЙ ИНСТАНС приложения. Инстансы
# не умеют быть табами друг друга ни при какой настройке табов, поэтому каждое
# расщепление плодило ещё одно окно. Замер 04.09.2026: четыре живых процесса
# Ghostty, три из них с `--working-directory=` — то есть порождённые сплитами.
#
# Ghostty объявляет `.sh` своим типом документа (`CFBundleDocumentTypes`,
# «Terminal scripts») и по умолчанию открывает такой файл НОВЫМ ТАБОМ текущего
# окна (`macos-dock-drop-behavior = new-tab`). Значит команду нельзя склеивать в
# аргументы: её надо положить в файл и отдать ФАЙЛ работающему приложению.
#
# Замер там же: файл ушёл в инстанс 1454 (основной), хотя звали из 39549. То
# есть LaunchServices несёт к главному инстансу, а не к вызывающему, — и для
# уклада «одно окно, много табов» это верное поведение: таб появляется там, где
# человек работает, независимо от того, из какого окна сработало расщепление.
#
# Побочно это чинит наследование окружения ПО ПОСТРОЕНИЮ. Прежде `open -na`
# передавал окружение ВЫЗЫВАЮЩЕГО процесса — сессии Claude, — и свежая сессия
# рождалась помеченной как дочерняя к ней: `CLAUDE_CODE_CHILD_SESSION=1` глушил
# запись транскрипта ЦЕЛИКОМ. Теперь launcher запускает Ghostty, а не сессия, и
# `CLAUDE_CODE_*` до него не доезжают вовсе (проверено: в порождённом табе они
# пусты). Скраб ниже остаётся страховкой — на случай, если сам Ghostty однажды
# окажется запущен из сессии, — но несущим он быть перестал.
scrub='unset CLAUDE_CODE_CHILD_SESSION CLAUDE_CODE_SESSION_ID'
scrub="$scrub CLAUDE_CODE_BRIDGE_SESSION_ID CLAUDE_CODE_MESSAGING_SOCKET"
scrub="$scrub CLAUDE_CODE_MESSAGING_TOKEN CLAUDE_CODE_ENTRYPOINT"

launch_dir="${TMPDIR:-/tmp}/derflow-hand"
mkdir -p "$launch_dir"
# Launcher не удаляет сам себя: удалять файл, который зачитывает исполняющая его
# оболочка, — гонка. Метём по возрасту при следующем запуске.
find "$launch_dir" -name 'hand-*.sh' -type f -mtime +1 -delete 2>/dev/null || true
launcher="$launch_dir/hand-$$.sh"

cat > "$launcher" <<LAUNCHER
#!/bin/zsh
$scrub
# PATH родителя — см. разбор выше. Без этой строки таб получает голый PATH
# Ghostty, в котором клиента нет.
#
# Обратных кавычек и \$ в тексте ЭТОГО heredoc быть не должно: он
# неквотированный, и обе конструкции сработают при генерации. Наступлено
# 12.09.2026 — слово в обратных кавычках запустило сам клиент.
export PATH=$q_path
cd $q_dir || exit 1
if ! command -v $q_claude >/dev/null 2>&1; then
  echo "❌ claude не найден — сессия не стартует"
  echo "искали: $q_claude"
  echo "PATH=\$PATH"
  exec zsh -i          # держим таб открытым, иначе ошибка мигнёт и исчезнет
fi
exec $q_claude --name $q_sess $q_prompt
LAUNCHER
chmod +x "$launcher"

if [ "$dry" = 1 ]; then
  echo "launcher: $launcher"
  sed 's/^/    /' "$launcher"
  # Доставка сменилась (см. разбор ниже) — сухой прогон обязан называть ту, что
  # действительно исполнится, иначе он врёт ровно о проверяемом месте.
  echo "доставка: new tab в окне родителя; последний рубеж — open -a Ghostty.app"
  rm -f "$launcher"
  exit 0
fi
# Новый таб встаёт рядом с ВЫБРАННЫМ, а нужен — рядом с родительским.
# `window-new-tab-position = current` в ~/.config/ghostty/config необходимо, но
# недостаточно: человек не сидит на родительском табе. Замер 05.09.2026 —
# родителем был таб 5 («◐ C·детектор дрейфа канона»), а выбран был таб 10.
# Недостающее звено — выбрать родителя ПЕРЕД открытием.
#
# 🔴 v4.26: опознавать родителя ПО ИМЕНИ ПРЕЕМНИКА неверно by design. Имя берётся
# из «имя:» хендоффа и описывает СЛЕДУЮЩУЮ задачу, а родительский таб назван
# своей; совпадают они только в цепочке «та же задача дальше». Боевое 06.09.2026:
# родитель — безымянная сессия по канону derflow, преемник — «C·память в
# ворктри», совпадений 0, честное предупреждение напечаталось, таб встал в конце.
# Проверка на фикстуре этого не ловила: там имя задавалось обоим.
#
# Родитель опознаётся СВОИМ ТАБОМ, а не именем: hand.sh запущен ИЗ него, значит
# у процесса сессии есть tty, и запись OSC-заголовка в /dev/ttysNNN метит ровно
# тот таб. Прежний тупик «метку через OSC не послать» касался `/dev/tty` — у
# Bash под агентом нет УПРАВЛЯЮЩЕГО терминала; путь к устройству берётся из
# `ps` по $CLAUDE_PID (или подъёмом по ppid) и открывается на запись.
#
# Метка временная: снимок заголовков → пометка → выбор → возврат заголовка.
# Возврат — по id таба из снимка. Если Claude перерисует заголовок раньше, чем
# мы прочитаем, метка не найдётся и мы падаем в прежнее поведение; висящей она
# не остаётся: заголовок к тому моменту уже перерисован (значок ✳/◐ меняется на
# каждой смене состояния сессии).
gh_snapshot() {
  osascript 2>/dev/null <<'AS' || true
tell application "Ghostty"
  set out to ""
  repeat with w in windows
    repeat with t in tabs of w
      set out to out & "ID:" & (id of t) & linefeed & "NM:" & (name of t) & linefeed
    end repeat
  end repeat
  return out
end tell
AS
}

# tty родителя: у самой оболочки под агентом его нет («??»), поэтому поднимаемся
# по дереву процессов до первого предка, у которого он есть.
parent_tty=""
_pid="${CLAUDE_PID:-$$}"
for _ in 1 2 3 4 5 6 7 8; do
  case "$_pid" in ''|0|1) break ;; esac
  _t="$(ps -o tty= -p "$_pid" 2>/dev/null | tr -d ' ')"
  case "$_t" in
    ''|'??') _pid="$(ps -o ppid= -p "$_pid" 2>/dev/null | tr -d ' ')" ;;
    *) parent_tty="/dev/$_t"; break ;;
  esac
done

# 🔴 Метка живёт секунды и её стирает САМ Claude: значок состояния (✳ покой,
# ◐/◑ работа) перерисовывается постоянно, и заголовок вместе с ним. Замер —
# один прогон из пяти терял метку между записью и чтением. Отсюда две вещи:
# метка переписывается ПЕРЕД каждой попыткой чтения (окно гонки — миллисекунды
# вместо четверти секунды), и без снимка заголовков метка не ставится вовсе.
# Пустой снимок (Ghostty не отвечает по AppleScript) означал бы пометку, которую
# нечем снять: ровно так таб и остался с «derflow-parent-…» на экране.
picked=0
parent_win=""
if [ -n "$parent_tty" ] && [ -w "$parent_tty" ]; then
  snap="$(gh_snapshot)"
  [ -n "$snap" ] || echo "⚠️  Ghostty не отвечает по AppleScript — метку не ставлю" >&2
fi
if [ -n "$parent_tty" ] && [ -w "$parent_tty" ] && [ -n "${snap:-}" ]; then
  mark="derflow-parent-$$-${RANDOM}"
  mid=""
  for _ in 1 2 3 4 5; do
    printf '\033]0;%s\007' "$mark" > "$parent_tty" 2>/dev/null || true
    sleep 0.12
    mid="$(osascript 2>/dev/null <<AS || true
tell application "Ghostty"
  repeat with w in windows
    repeat with t in tabs of w
      if (name of t) contains "$mark" then
        select tab t
        return ((id of w) & "|" & (id of t)) as text
      end if
    end repeat
  end repeat
  return ""
end tell
AS
)"
    [ -n "$mid" ] && break
  done
  # Окно родителя — вторая половина ответа. Выбрать таб мало: доставка обязана
  # НАЗВАТЬ окно, иначе она уедет в переднее (см. блок доставки ниже).
  case "$mid" in *'|'*) parent_win="${mid%%|*}"; mid="${mid##*|}" ;; esac
  if [ -n "$mid" ]; then
    old="$(printf '%s\n' "$snap" | awk -v id="$mid" \
      '/^ID:/{cur=substr($0,4)} /^NM:/{if(cur==id){print substr($0,4); exit}}')"
    if [ -n "$old" ]; then
      printf '\033]0;%s\007' "$old" > "$parent_tty" 2>/dev/null || true
    else
      echo "⚠️  заголовок родителя не восстановить — снимок его не знал;" >&2
      echo "    Claude перепишет его сам на следующей смене состояния." >&2
    fi
    picked=1
    echo "родительский таб опознан по tty ($parent_tty), окно $parent_win"
  fi
fi

# Фолбэк — прежнее опознание по имени. Оно верно ровно в цепочке «та же задача
# дальше», и остаётся на случай, когда tty недоступен (Ghostty не тот терминал,
# запуск не из сессии). Совпадений не ровно одно → не двигаем фокус вовсе:
# угаданный родитель хуже отсутствующего.
if [ "$picked" = 0 ]; then
  as_sess="$(printf '%s' "$sess" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g')"
  hits="$(osascript 2>/dev/null <<AS || true
tell application "Ghostty"
  set foundT to {}
  set foundW to {}
  repeat with w in windows
    repeat with t in tabs of w
      if (name of t) contains "$as_sess" then
        set end of foundT to t
        set end of foundW to w
      end if
    end repeat
  end repeat
  if (count of foundT) is 1 then
    select tab (item 1 of foundT)
    return "1|" & (id of (item 1 of foundW))
  end if
  return (count of foundT) as text
end tell
AS
)"
  case "$hits" in *'|'*) parent_win="${hits##*|}"; hits="${hits%%|*}" ;; esac
  case "$hits" in
    1) echo "родительский таб «${sess}» опознан по имени, окно $parent_win" ;;
    ""|0) echo "⚠️  родителя не опознать: tty нет и таба «${sess}» нет —" >&2
          echo "    новый встанет по умолчанию, не рядом" >&2 ;;
    *) echo "⚠️  табов с именем «${sess}»: ${hits} — родитель неоднозначен," >&2
       echo "    новый встанет по умолчанию: угадывать хуже, чем не двигать фокус." >&2 ;;
  esac
fi

# 🔴 Доставка НАЗЫВАЕТ окно, а не надеется на переднее (v4.35).
#
# Боевое 12.09.2026: родитель был опознан верно («выбран по tty /dev/ttys009»),
# и таб всё равно встал в ДРУГОМ ОКНЕ — там, где в тот момент смотрел человек.
# Словарь Ghostty различает две вещи, а скрипт знал одну: `select tab` выбирает
# таб В ЕГО ОКНЕ и окно вперёд НЕ выводит, а `open -a` отдаёт документ
# ПЕРЕДНЕМУ окну. Пока оба окна совпадали, подмена не замечалась.
#
# Ghostty 1.3.1 умеет `new tab in <окно> with configuration` — назначение
# задаётся явно, фокус в расчёте не участвует. Замер: два пробных таба легли
# ровно в названные окна, включая непереднее. Позиция внутри окна по-прежнему
# от `window-new-tab-position = current`, поэтому родителя всё равно надо
# выбрать ДО создания — это выше и делается.
#
# 🔴 Второе, что вскрылось тем же опытом: `open -a Ghostty.app <файл>` умеет
# вернуть 0 и не сделать ничего НАБЛЮДАЕМОГО. Первая редакция этой записи
# назвала отказ тихим — неверно: через много минут запуск всё-таки приехал, и
# приехал НОВЫМ ОКНОМ, а не табом. То есть отказ отложенный и не той формы, а
# скрипт не может его увидеть вовсе: `open` к тому моменту давно вернул 0.
# Поэтому LaunchServices оставлен только последним рубежом.
asq() { printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'; }
as_launcher="$(asq "$launcher")"
as_dir="$(asq "$dir")"

# deliver <id окна|пусто> → id нового таба, либо пусто. Пусто на входе — переднее
# окно: таб без опознанного родителя всё же лучше молчания.
deliver() {
  osascript 2>/dev/null <<AS || true
tell application "Ghostty"
  set target to missing value
  if "$1" is "" then
    set target to front window
  else
    repeat with w in windows
      if (id of w) is "$1" then set target to w
    end repeat
  end if
  if target is missing value then return ""
  set cfg to new surface configuration
  set command of cfg to "$as_launcher"
  set initial working directory of cfg to "$as_dir"
  set wait after command of cfg to true
  set nt to new tab in target with configuration cfg
  activate window target
  select tab nt
  return (id of nt) as text
end tell
AS
}

opened="$(deliver "$parent_win")"
if [ -n "$opened" ] && [ -n "$parent_win" ]; then
  echo "таб открыт рядом с родителем: окно $parent_win, таб $opened"
elif [ -n "$opened" ]; then
  echo "⚠️  родитель не опознан — таб открыт в ПЕРЕДНЕМ окне ($opened)," >&2
  echo "    рядом с родителем он не гарантирован." >&2
else
  # Без `-n`. Именно его отсутствие и делает это табом, а не новым инстансом.
  open -a Ghostty.app "$launcher"
  echo "⚠️  прямая доставка не отработала (Ghostty старше 1.3.1?) — отдал файл" >&2
  echo "    через LaunchServices. Исход тут НЕ проверяем: сессия может приехать" >&2
  echo "    с задержкой в минуты и отдельным ОКНОМ, а может не приехать совсем." >&2
  echo "    Не увидел её рядом — считай расщепление несостоявшимся и зови снова." >&2
fi
